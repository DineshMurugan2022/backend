const { test } = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');
const { once, EventEmitter } = require('node:events');
const { Server } = require('socket.io');
const { io: client } = require('socket.io-client');
const { DesktopRelay } = require('../services/desktopRelay');
const { issueTicket } = require('../services/desktopGsm');
const { startAgent } = require('../../huawei-e173-test/lib/agent');
process.env.JWT_SECRET = 'test-only-desktop-relay-secret';
const until = async predicate => { for (let i=0; i<100; i++) { if(predicate()) return; await new Promise(r=>setTimeout(r,20)); } assert.fail('Timed out'); };
test('desktop tickets bind two modem engines to separate authenticated accounts', async t => {
  const server=http.createServer(), io=new Server(server), saved=[];
  const relay=new DesktopRelay({saveCall:async(user,entry)=>saved.push({user,entry})});
  const cleanup=relay.attach(io);
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const url=`http://127.0.0.1:${server.address().port}`;
  const agents=[];
  t.after(async()=>{for(const a of agents)await a.stop();cleanup();await new Promise(r=>io.close(r));});
  const create=async user=>{
    const modem=new EventEmitter();modem.state={call:'idle',connected:false};modem.history=[];modem.logs=[];
    modem.snapshot=()=>({...modem.state,history:modem.history});
    modem.update=patch=>{Object.assign(modem.state,patch);modem.emit('state',modem.snapshot());};
    modem.connect=async settings=>{modem.settings=settings;modem.update({connected:true});};
    modem.disconnect=async()=>modem.update({connected:false,call:'idle'});
    modem.dial=async number=>modem.update({number,call:'dialing'});
    modem.answer=async()=>modem.update({call:'active'});
    const agent=startAgent(modem,{backendUrl:url,io:client,ticket:issueTicket(user,'https://bnycrm1.vercel.app'),scanInterval:30,onCode:()=>assert.fail('No pairing codes'),audioDevices:()=>[],listPorts:async()=>[{path:'COM4',friendlyName:'HUAWEI PC UI'},{path:'COM5',friendlyName:'HUAWEI Application'}]});
    agents.push(agent);await until(()=>agent.status().paired);return {modem,agent};
  };
  const a=await create('alice'),b=await create('bob');
  await until(()=>a.modem.state.connected&&b.modem.state.connected);
  await relay.action('alice','dial',{number:'123456'});assert.equal(b.modem.state.number,undefined);
  b.modem.update({call:'ringing',number:'987654'});
  await until(()=>relay.state('bob').number==='987654');assert.equal(relay.state('alice').number,'123456');
  assert.equal(relay.state('eve').number,'');await assert.rejects(relay.action('eve','answer'));
  a.modem.history=[{id:'call-a',number:'123456',direction:'outgoing',duration:1,time:new Date().toISOString()}];a.modem.emit('state',a.modem.snapshot());
  await until(()=>saved.length===1);assert.equal(saved[0].user,'alice');
  relay.release('alice');await until(()=>!a.agent.status().paired);assert.equal(relay.state('bob').isHostOnline,true);
  const invalid=client(`${url}/gsm-desktop`,{auth:{ticket:'fake'},transports:['websocket'],reconnection:false});
  await once(invalid,'connect_error');invalid.disconnect();
});
